//! Coalesce native window changes, rather than querying AppKit on every UI tick.
use std::cell::Cell;

#[derive(Default, Clone, Copy)]
pub struct Mode {
    pub fullscreen: bool,
    pub maximized: bool,
}

pub struct WindowState {
    dirty: Cell<bool>,
    mode: Cell<Mode>,
    queries: Cell<u64>,
    querying: Cell<bool>,
    size: Cell<Option<(u32, u32)>>,
    position: Cell<Option<(i32, i32)>>,
}

impl Default for WindowState {
    fn default() -> Self {
        Self {
            dirty: Cell::new(true),
            mode: Cell::new(Mode::default()),
            queries: Cell::new(0),
            querying: Cell::new(false),
            size: Cell::new(None),
            position: Cell::new(None),
        }
    }
}

impl WindowState {
    pub fn invalidate(&self) {
        // Winit's borderless AppKit query temporarily changes styleMask. Ignore
        // synchronous notifications generated by that query itself.
        if !self.querying.get() {
            self.dirty.set(true);
        }
    }
    pub fn resized(&self, width: u32, height: u32) {
        if self.size.replace(Some((width, height))) != Some((width, height)) {
            self.invalidate();
        }
    }
    pub fn moved(&self, x: i32, y: i32) {
        if self.position.replace(Some((x, y))) != Some((x, y)) {
            self.invalidate();
        }
    }
    pub fn mode(&self) -> Mode {
        self.mode.get()
    }
    pub fn queries(&self) -> u64 {
        self.queries.get()
    }
    pub fn refresh(&self, query: impl FnOnce() -> Option<Mode>) -> Option<Mode> {
        if !self.dirty.replace(false) {
            return None;
        }
        // Run after the event filter returns, outside the backend's event borrow.
        self.querying.set(true);
        let mode = query();
        self.querying.set(false);
        let Some(mode) = mode else {
            self.invalidate();
            return None;
        };
        self.queries.set(self.queries.get() + 1);
        self.mode.set(mode);
        Some(mode)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn idle_ticks_do_not_query_native_window_and_events_coalesce() {
        let state = WindowState::default();
        state.refresh(|| Some(Mode::default()));
        for _ in 0..1000 {
            assert!(state.refresh(|| panic!("idle native query")).is_none());
        }
        for _ in 0..100 {
            state.invalidate();
        }
        let mode = state
            .refresh(|| {
                Some(Mode {
                    fullscreen: false,
                    maximized: true,
                })
            })
            .unwrap();
        assert!(mode.maximized);
        assert!(state.mode().maximized);
        assert_eq!(state.queries(), 2);
    }
    #[test]
    fn missing_native_window_retries_initial_sync() {
        let state = WindowState::default();
        assert!(state.refresh(|| None).is_none());
        assert_eq!(state.queries(), 0);
        assert!(state.refresh(|| Some(Mode::default())).is_some());
    }
    #[test]
    fn duplicate_geometry_and_query_generated_events_do_not_loop() {
        let state = WindowState::default();
        state.resized(1000, 640);
        state.moved(20, 30);
        state.refresh(|| {
            state.invalidate();
            Some(Mode::default())
        });
        for _ in 0..1000 {
            state.resized(1000, 640);
            state.moved(20, 30);
            assert!(state.refresh(|| panic!("duplicate event query")).is_none());
        }
        state.resized(1100, 700);
        assert!(state.refresh(|| Some(Mode::default())).is_some());
        assert_eq!(state.queries(), 2);
    }
}
